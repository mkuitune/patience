use patience_core::{MoveError, StateError};

#[derive(Clone, Copy)]
pub enum Key {
    Settings,
    Language,
    Close,
    NewGame,
    Undo,
    Help,
    Teach,
    ExpandLayout,
    CenterLayout,
    Won,
    Draw,
    SaveError,
    InvalidLinkHelp,
    CannotHome,
    InvalidSource,
    InvalidDestination,
    SameColumn,
    KingRequired,
    SameColor,
    WrongRank,
    FoundationSingleCard,
    FoundationWrongSuit,
    FoundationWrongRank,
    EmptyStock,
    UnsupportedVersion,
    InvalidState,
    HelpDeck,
    HelpGoalTitle,
    HelpGoal,
    HelpPlayTitle,
    HelpPlay,
    HelpRulesTitle,
    HelpTeach,
    HelpUndo,
    HelpHomeEmpty,
    HelpHomeBuilding,
    HelpHomeComplete,
    HelpStockTitle,
    HelpStock,
}

pub struct Language {
    pub code: &'static str,
    pub name: &'static str,
    pub title: &'static str,
    messages: [&'static str; Key::HelpStock as usize + 1],
}

impl Language {
    pub fn text(&self, key: Key) -> &'static str {
        self.messages[key as usize]
    }
    pub fn move_error(&self, error: MoveError) -> &'static str {
        self.text(match error {
            MoveError::InvalidSource => Key::InvalidSource,
            MoveError::InvalidDestination => Key::InvalidDestination,
            MoveError::SameColumn => Key::SameColumn,
            MoveError::KingRequired => Key::KingRequired,
            MoveError::SameColor => Key::SameColor,
            MoveError::WrongRank => Key::WrongRank,
            MoveError::FoundationSingleCard => Key::FoundationSingleCard,
            MoveError::FoundationWrongSuit => Key::FoundationWrongSuit,
            MoveError::FoundationWrongRank => Key::FoundationWrongRank,
            MoveError::EmptyStock => Key::EmptyStock,
        })
    }
    pub fn state_error(&self, error: StateError) -> &'static str {
        self.text(match error {
            StateError::UnsupportedVersion => Key::UnsupportedVersion,
            StateError::InvalidState => Key::InvalidState,
        })
    }
}

pub fn by_code(code: &str) -> &'static Language {
    LANGUAGES
        .iter()
        .find(|language| language.code == code)
        .unwrap_or(&LANGUAGES[0])
}

