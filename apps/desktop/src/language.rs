#[cfg(test)]
mod tests {
    use super::*;
    use eframe::egui;

    #[test]
    fn catalogs_are_complete_unique_and_supported_by_the_bundled_font() {
        let ctx = egui::Context::default();
        let _ = ctx.run(egui::RawInput::default(), |ctx| {
            ctx.fonts_mut(|fonts| {
                for (index, language) in LANGUAGES.iter().enumerate() {
                    assert!(
                        !LANGUAGES[..index]
                            .iter()
                            .any(|other| other.code == language.code)
                    );
                    for text in std::iter::once(language.name).chain(language.messages) {
                        assert!(!text.trim().is_empty(), "empty text in {}", language.code);
                        assert!(
                            fonts.has_glyphs(&egui::FontId::proportional(16.0), text),
                            "unsupported glyph in {}: {text}",
                            language.code
                        );
                    }
                }
            });
        });
        assert_eq!(by_code("unsupported").code, "en");
    }
}
