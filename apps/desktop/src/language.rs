#[cfg(test)]
mod tests {
    use super::*;
    use eframe::egui;

    #[test]
    fn catalogs_are_complete_unique_and_supported_by_the_bundled_font() {
        let official_eu_languages = [
            "bg", "hr", "cs", "da", "nl", "en", "et", "fi", "fr", "de", "el", "hu", "ga", "it",
            "lv", "lt", "mt", "pl", "pt", "ro", "sk", "sl", "es", "sv",
        ];
        assert_eq!(LANGUAGES.len(), official_eu_languages.len());
        for code in official_eu_languages {
            assert_eq!(by_code(code).code, code, "missing language: {code}");
        }
        let ctx = egui::Context::default();
        let _ = ctx.run(egui::RawInput::default(), |ctx| {
            ctx.fonts_mut(|fonts| {
                for (index, language) in LANGUAGES.iter().enumerate() {
                    assert!(
                        !LANGUAGES[..index]
                            .iter()
                            .any(|other| other.code == language.code)
                    );
                    for text in [language.name, language.title]
                        .into_iter()
                        .chain(language.messages)
                    {
                        assert!(!text.trim().is_empty(), "empty text in {}", language.code);
                        assert!(
                            fonts.has_glyphs(&egui::FontId::proportional(16.0), text),
                            "unsupported glyph in {}: {text}",
                            language.code
                        );
                    }
                }
            });
        });
        assert_eq!(by_code("unsupported").code, "en");
    }
}
